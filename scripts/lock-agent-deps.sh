#!/usr/bin/env bash
# Lock the agent image's Python dependencies: every package (top-level and
# transitive) pinned by version and SHA-256, for the image's platform only
# (CPython 3.14, Linux x86-64, glibc). Binary wheels only: nothing is built.
# The lock is needed because transitive versions drift (langsmith moved
# between 11/23 and 11/24 in the ADR 0002 spike).
#
# Usage: scripts/lock-agent-deps.sh   (writes agent/requirements.lock)
# Downloads into build/agent-image/lock-wheels/ (gitignored). Rerun only to
# change versions; the build installs from the lock with --require-hashes.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PY_VERSION="${PY_VERSION:-3.14}"
dir="$ROOT/build/agent-image/lock-wheels"
rm -rf "$dir" && mkdir -p "$dir"

python3 -m pip download -q --disable-pip-version-check --only-binary=:all: \
  --python-version "$PY_VERSION" --implementation cp \
  --platform manylinux_2_28_x86_64 --platform manylinux_2_17_x86_64 --platform manylinux2014_x86_64 \
  -d "$dir" -r "$ROOT/agent/requirements.in"

python3 - "$dir" "$ROOT/agent/requirements.lock" "$PY_VERSION" <<'EOF'
import hashlib, pathlib, sys
d, out, pyv = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2]), sys.argv[3]
lines = [f"# Generated by scripts/lock-agent-deps.sh: CPython {pyv}, Linux x86-64 (glibc),",
         "# binary wheels only. Do not edit by hand.", ""]
for w in sorted(d.glob("*.whl"), key=lambda p: p.name.lower()):
    name, version = w.name.split("-")[:2]
    h = hashlib.sha256(w.read_bytes()).hexdigest()
    lines.append(f"{name.lower().replace('_', '-')}=={version} \\\n    --hash=sha256:{h}")
out.write_text("\n".join(lines) + "\n")
print(f"{len(list(d.glob('*.whl')))} packages locked -> {out}")
EOF
